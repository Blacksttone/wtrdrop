-- Monthly fee of one branch for a month (0 in the account's first calendar month).
create or replace function public.branch_platform_fee(p_customer_id uuid, p_month date) returns numeric
language plpgsql stable security definer set search_path = public as $$
declare
  c public.customers;
  a public.customer_accounts;
  pr public.platform_pricing;
  v_month date := date_trunc('month', p_month)::date;
  v_branches integer;
  v_head uuid;
begin
  select * into pr from public.platform_pricing;
  if not coalesce(pr.fees_enabled, false) then
    return 0;
  end if;
  select * into c from public.customers where id = p_customer_id;
  if c.id is null or c.account_id is null or c.status <> 'active' then
    return 0;  -- offline customers (no app) pay no service fee
  end if;
  select * into a from public.customer_accounts where id = c.account_id;
  if date_trunc('month', a.created_at at time zone 'Asia/Kolkata')::date >= v_month
     or date_trunc('month', c.created_at at time zone 'Asia/Kolkata')::date >= v_month then
    return 0;  -- the calendar month of joining is free
  end if;
  if a.account_type = 'home' then
    return pr.home_fee;
  elsif a.account_type = 'store' then
    return pr.store_branch_fee;
  end if;
  select count(*), (array_agg(id order by created_at, (bill_to_customer_id is not null), id))[1] into v_branches, v_head
  from public.customers where account_id = a.id and status = 'active';
  if v_branches <= 1 then
    return pr.company_single_fee;
  end if;
  return case when c.id = v_head then pr.company_head_fee else pr.company_extra_branch_fee end;
end $$;

-- Monthly "Waterdrop bill" for suppliers (payable to the app owner).
create table public.platform_invoices (
  id uuid primary key default gen_random_uuid(),
  supplier_id uuid not null references public.suppliers (id) on delete restrict,
  invoice_number text not null unique,
  month date not null check (month = date_trunc('month', month)::date),
  subscription_fee numeric(12,2) not null default 0,
  coworkers integer not null default 0,
  coworker_fee numeric(12,2) not null default 0,
  customer_fees numeric(12,2) not null default 0,
  customer_fees_settled_online numeric(12,2) not null default 0,
  total numeric(12,2) not null default 0,
  status text not null default 'unpaid' check (status in ('unpaid', 'paid', 'waived')),
  due_date date not null,
  paid_at timestamptz,
  payment_reference text check (payment_reference is null or char_length(payment_reference) <= 120),
  marked_by uuid references public.profiles (id),
  generated_at timestamptz not null default now(),
  constraint platform_invoices_month_uq unique (supplier_id, month)
);
alter table public.platform_invoices enable row level security;
create policy platform_invoices_select on public.platform_invoices for select to authenticated using (
  supplier_id = public.my_manager_supplier_id() or public.is_admin()
);
revoke insert, update, delete on public.platform_invoices from authenticated;
revoke all on public.platform_invoices from anon;

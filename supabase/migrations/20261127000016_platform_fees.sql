-- =====================================================================
-- Waterdrop — platform service fees (the app owner's income).
--  * Customers: a monthly "Waterdrop service fee" per branch, added to the
--    supplier's bill: Home ₹59, Store ₹99 per branch, Company ₹99 (1 branch)
--    or ₹149 for the first branch + ₹99 for every other branch.
--  * Suppliers: ₹359 a month + ₹29 per co-worker, plus the customer service
--    fees they collected themselves (cash / direct UPI), on a monthly
--    "Waterdrop bill" payable to the app owner.
--  * The calendar month someone joins is free.
-- Prices live in platform_pricing and are editable by the admin.
-- GENERATED by scripts/gen-migration-16.py (do not edit by hand).
-- =====================================================================

create table public.platform_pricing (
  id boolean primary key default true check (id),
  home_fee numeric(10,2) not null default 59 check (home_fee >= 0),
  store_branch_fee numeric(10,2) not null default 99 check (store_branch_fee >= 0),
  company_single_fee numeric(10,2) not null default 99 check (company_single_fee >= 0),
  company_head_fee numeric(10,2) not null default 149 check (company_head_fee >= 0),
  company_extra_branch_fee numeric(10,2) not null default 99 check (company_extra_branch_fee >= 0),
  supplier_fee numeric(10,2) not null default 359 check (supplier_fee >= 0),
  coworker_fee numeric(10,2) not null default 29 check (coworker_fee >= 0),
  fees_enabled boolean not null default true,
  owner_upi_id text check (owner_upi_id is null or owner_upi_id ~ '^[A-Za-z0-9._-]{2,200}@[A-Za-z]{2,64}$'),
  owner_payee_name text check (owner_payee_name is null or char_length(owner_payee_name) <= 100),
  updated_at timestamptz not null default now(),
  updated_by uuid references public.profiles (id)
);
insert into public.platform_pricing (id) values (true);
alter table public.platform_pricing enable row level security;
create policy platform_pricing_select on public.platform_pricing for select to authenticated using (true);
revoke insert, update, delete on public.platform_pricing from authenticated;
revoke all on public.platform_pricing from anon;

-- Service-fee lines on customer invoices (one per branch per month).
alter table public.invoices add column platform_fee numeric(12,2) not null default 0 check (platform_fee >= 0);
alter table public.invoice_items
  add column fee_customer_id uuid references public.customers (id) on delete restrict,
  add column fee_month date check (fee_month is null or fee_month = date_trunc('month', fee_month)::date);
alter table public.invoice_items drop constraint invoice_items_source_ck;
alter table public.invoice_items add constraint invoice_items_source_ck
  check (num_nonnulls(delivery_id, delivery_adjustment_id, fee_month) = 1
         and (fee_month is null) = (fee_customer_id is null));
create unique index invoice_items_fee_uq on public.invoice_items (fee_customer_id, fee_month) where fee_month is not null;

-- Monthly fee of one branch for a month (0 in the account's first calendar month).
create or replace function public.branch_platform_fee(p_customer_id uuid, p_month date) returns numeric
language plpgsql stable security definer set search_path = public as $$
declare
  c public.customers;
  a public.customer_accounts;
  pr public.platform_pricing;
  v_month date := date_trunc('month', p_month)::date;
  v_branches integer;
  v_head uuid;
begin
  select * into pr from public.platform_pricing;
  if not coalesce(pr.fees_enabled, false) then
    return 0;
  end if;
  select * into c from public.customers where id = p_customer_id;
  if c.id is null or c.account_id is null or c.status <> 'active' then
    return 0;  -- offline customers (no app) pay no service fee
  end if;
  select * into a from public.customer_accounts where id = c.account_id;
  if date_trunc('month', a.created_at at time zone 'Asia/Kolkata')::date >= v_month
     or date_trunc('month', c.created_at at time zone 'Asia/Kolkata')::date >= v_month then
    return 0;  -- the calendar month of joining is free
  end if;
  if a.account_type = 'home' then
    return pr.home_fee;
  elsif a.account_type = 'store' then
    return pr.store_branch_fee;
  end if;
  select count(*), (array_agg(id order by created_at, (bill_to_customer_id is not null), id))[1] into v_branches, v_head
  from public.customers where account_id = a.id and status = 'active';
  if v_branches <= 1 then
    return pr.company_single_fee;
  end if;
  return case when c.id = v_head then pr.company_head_fee else pr.company_extra_branch_fee end;
end $$;

-- Monthly "Waterdrop bill" for suppliers (payable to the app owner).

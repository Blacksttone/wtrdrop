  supplier_id uuid not null references public.suppliers (id) on delete restrict,
  invoice_number text not null unique,
  month date not null check (month = date_trunc('month', month)::date),
  subscription_fee numeric(12,2) not null default 0,
  coworkers integer not null default 0,
  coworker_fee numeric(12,2) not null default 0,
  customer_fees numeric(12,2) not null default 0,
  customer_fees_settled_online numeric(12,2) not null default 0,
  total numeric(12,2) not null default 0,
  status text not null default 'unpaid' check (status in ('unpaid', 'paid', 'waived')),
  due_date date not null,
  paid_at timestamptz,
  payment_reference text check (payment_reference is null or char_length(payment_reference) <= 120),

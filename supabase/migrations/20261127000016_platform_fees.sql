-- Customer bills now carry the Waterdrop service fee lines.
create or replace function public.generate_invoice_for_customer(
  p_customer_id uuid, p_period_start date, p_period_end date, p_invoice_date date default current_date
) returns uuid
language plpgsql security definer set search_path = public as $$
declare
  c public.customers;
  sup public.suppliers;
  st public.supplier_settings;
  prev public.invoices;
  v_existing uuid;
  v_inv uuid;
  v_number text;
  v_seq integer;
  v_qty integer;
  v_subtotal numeric;
  v_tax numeric;
  v_payments numeric;
  v_credits numeric;
  v_prev_balance numeric;
  v_due numeric;
  v_items integer;
  v_now timestamptz;
  v_multi boolean;
  v_fee numeric;
  v_fee_month date;
begin
  if p_period_end < p_period_start then
    raise exception 'Invalid billing period' using errcode = '22023';
  end if;
  -- Lock the customer: serializes billing with payments/credits for this account.
  select * into c from public.customers where id = p_customer_id for update;
  if c.id is null then
    raise exception 'Customer not found' using errcode = 'P0002';
  end if;
  -- Branches that bill to a head branch appear on the head branch's combined bill.
  if c.bill_to_customer_id is not null then
    return null;
  end if;
  v_multi := exists (select 1 from public.customers where bill_to_customer_id = c.id);

  select id into v_existing from public.invoices
   where customer_id = c.id and billing_period_start = p_period_start and billing_period_end = p_period_end;
  if v_existing is not null then
    return v_existing;   -- idempotent re-run
  end if;

  select * into sup from public.suppliers where id = c.supplier_id;
  select * into st from public.supplier_settings where supplier_id = c.supplier_id for update;
  select * into prev from public.invoices where customer_id = c.id order by generated_at desc limit 1;

  create temporary table if not exists _wd_items (
    delivery_id uuid, adjustment_id uuid, item_date date, description text, quantity integer, unit_price numeric, amount numeric,
    fee_customer_id uuid, fee_month date
  ) on commit drop;
  truncate _wd_items;

  insert into _wd_items
  select d.id, null, d.delivery_date,
         case when v_multi then coalesce(b.branch_name, b.customer_name) || ' – ' else '' end ||
         format('Water cans delivered (confirmed %s of %s expected)', d.confirmed_quantity, d.expected_quantity),
         d.confirmed_quantity, d.unit_price, round(d.confirmed_quantity * d.unit_price, 2), null, null
  from public.deliveries d join public.customers b on b.id = d.customer_id
  where (b.id = c.id or b.bill_to_customer_id = c.id) and d.status = 'confirmed' and d.delivery_date <= p_period_end
    and not exists (select 1 from public.invoice_items ii where ii.delivery_id = d.id);

  insert into _wd_items
  select null, a.id, (a.created_at at time zone c.timezone)::date,
         case when v_multi then coalesce(b.branch_name, b.customer_name) || ' – ' else '' end ||
         format('Delivery correction: %s', a.reason), a.delta, a.unit_price, round(a.delta * a.unit_price, 2), null, null
  from public.delivery_adjustments a join public.customers b on b.id = a.customer_id
  where (b.id = c.id or b.bill_to_customer_id = c.id) and (a.created_at at time zone c.timezone)::date <= p_period_end
    and not exists (select 1 from public.invoice_items ii where ii.delivery_adjustment_id = a.id);

  -- Waterdrop service fee: one line per branch for the billed month (first month free).
  v_fee_month := date_trunc('month', p_period_end)::date;
  insert into _wd_items
  select null, null, v_fee_month,
         case when v_multi then coalesce(b.branch_name, b.customer_name) || ' – ' else '' end ||
         'Waterdrop service fee – ' || to_char(v_fee_month, 'Mon YYYY'),
         1, f.fee, f.fee, b.id, v_fee_month
  from public.customers b
  cross join lateral (select public.branch_platform_fee(b.id, v_fee_month) as fee) f
  where (b.id = c.id or b.bill_to_customer_id = c.id) and f.fee > 0
    and not exists (select 1 from public.invoice_items ii where ii.fee_customer_id = b.id and ii.fee_month = v_fee_month);

  select count(*), coalesce(sum(quantity) filter (where fee_month is null), 0),
         coalesce(sum(amount) filter (where fee_month is null), 0), coalesce(sum(amount) filter (where fee_month is not null), 0)
    into v_items, v_qty, v_subtotal, v_fee from _wd_items;

  v_now := clock_timestamp();
  v_prev_balance := coalesce(prev.amount_due,
    (select sum(opening_balance) from public.customers where id in (select public.billing_group(c.id))), 0);
  select coalesce(sum(amount), 0) into v_payments from public.payments
   where customer_id in (select public.billing_group(c.id)) and status = 'succeeded'
     and (prev.id is null or received_at > prev.generated_at) and received_at <= v_now;
  select coalesce(sum(amount), 0) into v_credits from public.credit_notes
   where customer_id in (select public.billing_group(c.id)) and (prev.id is null or created_at > prev.generated_at) and created_at <= v_now;

  -- Nothing to bill and nothing carried: skip (safe to re-run later).
  if v_items = 0 and v_prev_balance = 0 and v_payments = 0 and v_credits = 0 then
    return null;
  end if;

  v_tax := round(v_subtotal * st.tax_rate / 100, 2);
  v_due := round(v_prev_balance + v_subtotal + v_tax + v_fee - v_payments - v_credits, 2);

  perform set_config('waterdrop.billing_engine', 'on', true);
  update public.supplier_settings set invoice_seq = invoice_seq + 1 where id = st.id returning invoice_seq into v_seq;
  perform set_config('waterdrop.billing_engine', 'off', true);
  v_number := st.invoice_prefix || '-' || sup.business_code || '-' || to_char(p_invoice_date, 'YYYYMM') || '-' || lpad(v_seq::text, 4, '0');

  insert into public.invoices (supplier_id, customer_id, invoice_number, invoice_date, billing_period_start,
    billing_period_end, total_quantity, subtotal, tax_rate, tax_amount, current_charges, previous_balance,
    payments_received, credits, amount_due, due_date, status, supplier_snapshot, customer_snapshot, generated_at, platform_fee)
  values (c.supplier_id, c.id, v_number, p_invoice_date, p_period_start, p_period_end, v_qty, v_subtotal,
    st.tax_rate, v_tax, v_subtotal + v_tax + v_fee, v_prev_balance, v_payments, v_credits, v_due,
    p_invoice_date + st.billing_due_days,
    case when v_due <= 0 then 'paid'::public.invoice_status else 'unpaid'::public.invoice_status end,
    jsonb_build_object('business_name', sup.business_name, 'owner_name', sup.owner_name, 'address', sup.address,
                       'phone', sup.phone, 'email', sup.email, 'logo_url', sup.logo_url, 'billing_info', sup.billing_info,
                       'business_code', sup.business_code, 'tax_label', st.tax_label),
    jsonb_build_object('customer_name', coalesce((select name from public.customer_accounts where id = c.account_id), c.customer_name),
                       'address', c.address, 'phone', c.phone, 'branch_name', c.branch_name,
                       'branches', (select jsonb_agg(coalesce(x.branch_name, x.customer_name) order by x.created_at)
                                    from public.customers x where x.id = c.id or x.bill_to_customer_id = c.id)),
    v_now, v_fee)
  returning id into v_inv;

  insert into public.invoice_items (invoice_id, delivery_id, delivery_adjustment_id, item_date, description, quantity, unit_price, amount,
                                    fee_customer_id, fee_month)
  select v_inv, delivery_id, adjustment_id, item_date, description, quantity, unit_price, amount, fee_customer_id, fee_month
  from _wd_items order by item_date, description;

  if prev.id is not null then
    update public.invoices set superseded_by = v_inv where id = prev.id;
    perform public.refresh_invoice_status(prev.id);
  end if;

  perform public.notify_customer(c.id, 'billing', 'bill_generated', 'info', 'Your monthly water bill is ready',
    format('Bill %s for %s – %s: %s cans. Amount due ₹%s by %s.', v_number, to_char(p_period_start, 'DD Mon'),
           to_char(p_period_end, 'DD Mon YYYY'), v_qty, to_char(v_due, 'FM999999990.00'),
           to_char(p_invoice_date + st.billing_due_days, 'DD Mon')),
    '/app/bills', jsonb_build_object('invoice_id', v_inv), 'bill:' || v_inv);
  update public.invoices set notified_at = now() where id = v_inv;
  perform public.write_audit('invoice.generated', 'invoice', v_inv, c.supplier_id,
    jsonb_build_object('number', v_number, 'amount_due', v_due, 'quantity', v_qty));
  return v_inv;
end $$;

-- Builds (or refreshes, while unpaid) a supplier's Waterdrop bill for a month.
create or replace function public.generate_platform_invoice(p_supplier_id uuid, p_month date) returns public.platform_invoices
language plpgsql security definer set search_path = public as $$
declare
  s public.suppliers;
  pr public.platform_pricing;
  pi public.platform_invoices;
  v_month date := date_trunc('month', p_month)::date;
  v_sub numeric := 0;
  v_staff integer := 0;
  v_cust numeric;
  v_online numeric;
  v_total numeric;
begin
  select * into s from public.suppliers where id = p_supplier_id;
  select * into pr from public.platform_pricing;
  if s.id is null then
    raise exception 'Supplier not found' using errcode = 'P0002';
  end if;
  select * into pi from public.platform_invoices where supplier_id = s.id and month = v_month;
  if pi.status in ('paid', 'waived') then
    return pi;  -- settled bills are never changed
  end if;
  if coalesce(pr.fees_enabled, false) and date_trunc('month', s.created_at at time zone 'Asia/Kolkata')::date < v_month then
    v_sub := pr.supplier_fee;
    select count(*) into v_staff from public.supplier_staff where supplier_id = s.id and status = 'active';
  end if;
  -- Service fees on this supplier's customer bills issued in the month.
  select coalesce(sum(platform_fee), 0) into v_cust from public.invoices
  where supplier_id = s.id and date_trunc('month', invoice_date)::date = v_month;
  v_online := 0;  -- Cashfree split payments (phase 2) will settle part of this automatically
  v_total := round(v_sub + v_staff * coalesce(pr.coworker_fee, 0) + v_cust - v_online, 2);

  insert into public.platform_invoices (supplier_id, invoice_number, month, subscription_fee, coworkers, coworker_fee,
                                        customer_fees, customer_fees_settled_online, total, status, due_date)
  values (s.id, 'WDP-' || s.business_code || '-' || to_char(v_month, 'YYYYMM'), v_month, v_sub, v_staff,
          v_staff * coalesce(pr.coworker_fee, 0), v_cust, v_online, v_total,
          case when v_total <= 0 then 'waived' else 'unpaid' end, (v_month + interval '1 month')::date + 9)
  on conflict (supplier_id, month) do update set
    subscription_fee = excluded.subscription_fee, coworkers = excluded.coworkers, coworker_fee = excluded.coworker_fee,
    customer_fees = excluded.customer_fees, customer_fees_settled_online = excluded.customer_fees_settled_online,
    total = excluded.total, status = excluded.status, generated_at = now()
  returning * into pi;
  return pi;
end $$;

-- Monthly job (1st of the month, India time): bills every supplier for the previous month.
create or replace function public.run_platform_billing(p_as_of date default null) returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_month date := (date_trunc('month', coalesce(p_as_of, (now() at time zone 'Asia/Kolkata')::date)) - interval '1 month')::date;
  s record;
  pi public.platform_invoices;
  n integer := 0;
begin
  for s in select id, owner_id from public.suppliers where status = 'active' loop
    pi := public.generate_platform_invoice(s.id, v_month);
    if pi.status = 'unpaid' and pi.total > 0 then
      perform public.notify(s.owner_id, 'payment_due', 'warning', 'Your Waterdrop bill is ready',
        format('Waterdrop bill for %s: ₹%s, due %s.', to_char(v_month, 'Mon YYYY'), to_char(pi.total, 'FM999999990.00'),
               to_char(pi.due_date, 'DD Mon')),
        '/supplier/waterdrop-bill', jsonb_build_object('platform_invoice_id', pi.id), 'platform-bill:' || pi.id);
      n := n + 1;
    end if;
  end loop;
  return n;
end $$;

-- Supplier: current month so far (an estimate) + past bills.
create or replace function public.my_platform_summary() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_sid uuid := public.my_manager_supplier_id();
  pr public.platform_pricing;
  s public.suppliers;
  v_month date := date_trunc('month', (now() at time zone 'Asia/Kolkata')::date)::date;
  v_staff integer;
  v_cust numeric;
  v_free boolean;
begin
  if v_sid is null then
    raise exception 'Only the owner or a manager can see the Waterdrop bill' using errcode = '42501';
  end if;
  select * into pr from public.platform_pricing;
  select * into s from public.suppliers where id = v_sid;
  v_free := date_trunc('month', s.created_at at time zone 'Asia/Kolkata')::date >= v_month or not pr.fees_enabled;
  select count(*) into v_staff from public.supplier_staff where supplier_id = v_sid and status = 'active';
  select coalesce(sum(platform_fee), 0) into v_cust from public.invoices
  where supplier_id = v_sid and date_trunc('month', invoice_date)::date = v_month;
  return jsonb_build_object(
    'month', v_month,
    'free_month', v_free,
    'subscription_fee', case when v_free then 0 else pr.supplier_fee end,
    'coworkers', v_staff,
    'coworker_fee', case when v_free then 0 else v_staff * pr.coworker_fee end,
    'customer_fees_so_far', v_cust,
    'estimate', case when v_free then 0 else pr.supplier_fee + v_staff * pr.coworker_fee end + v_cust,
    'prices', jsonb_build_object('supplier', pr.supplier_fee, 'coworker', pr.coworker_fee, 'home', pr.home_fee,
                                 'store_branch', pr.store_branch_fee, 'company_single', pr.company_single_fee,
                                 'company_head', pr.company_head_fee, 'company_extra_branch', pr.company_extra_branch_fee),
    'pay_to', jsonb_build_object('upi_id', pr.owner_upi_id, 'name', pr.owner_payee_name),
    'unpaid_total', (select coalesce(sum(total), 0) from public.platform_invoices where supplier_id = v_sid and status = 'unpaid')
  );
end $$;

-- Admin: prices.
create or replace function public.admin_update_pricing(p jsonb) returns public.platform_pricing
language plpgsql security definer set search_path = public as $$
declare r public.platform_pricing;
begin
  perform public.require_admin();
  update public.platform_pricing set
    home_fee = coalesce((p ->> 'home_fee')::numeric, home_fee),
    store_branch_fee = coalesce((p ->> 'store_branch_fee')::numeric, store_branch_fee),
    company_single_fee = coalesce((p ->> 'company_single_fee')::numeric, company_single_fee),
    company_head_fee = coalesce((p ->> 'company_head_fee')::numeric, company_head_fee),
    company_extra_branch_fee = coalesce((p ->> 'company_extra_branch_fee')::numeric, company_extra_branch_fee),
    supplier_fee = coalesce((p ->> 'supplier_fee')::numeric, supplier_fee),
    coworker_fee = coalesce((p ->> 'coworker_fee')::numeric, coworker_fee),
    fees_enabled = coalesce((p ->> 'fees_enabled')::boolean, fees_enabled),
    owner_upi_id = case when p ? 'owner_upi_id' then nullif(trim(p ->> 'owner_upi_id'), '') else owner_upi_id end,
    owner_payee_name = case when p ? 'owner_payee_name' then nullif(trim(p ->> 'owner_payee_name'), '') else owner_payee_name end,
    updated_at = now(), updated_by = auth.uid()
  where id  -- single settings row (Supabase rejects UPDATE without WHERE)
  returning * into r;
  perform public.write_audit('platform.pricing_updated', 'platform_pricing', null, null, p);
  return r;
end $$;

-- Admin: earnings overview + mark a supplier bill paid / waived.
create or replace function public.admin_platform_earnings(p_month date default null)
returns table (invoice_id uuid, supplier_id uuid, business_name text, month date, subscription_fee numeric, coworkers integer,
               coworker_fee numeric, customer_fees numeric, total numeric, status text, due_date date, paid_at timestamptz,
               payment_reference text)
language sql stable security definer set search_path = public as $$
  select pi.id, s.id, s.business_name, pi.month, pi.subscription_fee, pi.coworkers, pi.coworker_fee, pi.customer_fees,
         pi.total, pi.status, pi.due_date, pi.paid_at, pi.payment_reference
  from public.platform_invoices pi join public.suppliers s on s.id = pi.supplier_id
  where public.is_admin() and (p_month is null or pi.month = date_trunc('month', p_month)::date)
  order by pi.month desc, s.business_name;
$$;

create or replace function public.admin_set_platform_invoice_status(p_invoice_id uuid, p_status text, p_reference text default null)
returns public.platform_invoices
language plpgsql security definer set search_path = public as $$
declare pi public.platform_invoices;
begin
  perform public.require_admin();
  if p_status not in ('paid', 'unpaid', 'waived') then
    raise exception 'Status must be paid, unpaid or waived' using errcode = '22023';
  end if;
  update public.platform_invoices set status = p_status,
    paid_at = case when p_status = 'paid' then now() else null end,
    payment_reference = case when p_status = 'paid' then nullif(trim(coalesce(p_reference, '')), '') else null end,
    marked_by = auth.uid()
  where id = p_invoice_id returning * into pi;
  if pi.id is null then
    raise exception 'Bill not found' using errcode = 'P0002';
  end if;
  perform public.write_audit('platform.invoice_' || p_status, 'platform_invoice', pi.id, pi.supplier_id,
                             jsonb_build_object('total', pi.total, 'reference', pi.payment_reference));
  return pi;
end $$;

-- Admin: create / refresh bills now (e.g. to check this month's numbers).
create or replace function public.admin_generate_platform_invoices(p_month date) returns integer
language plpgsql security definer set search_path = public as $$
declare s record; n integer := 0;
begin
  perform public.require_admin();
  for s in select id from public.suppliers where status = 'active' loop
